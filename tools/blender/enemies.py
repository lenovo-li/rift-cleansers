def _claw_hand(p, d, color, r=0.045, fingers=3, length=0.09):
    """张开的爪手：掌 + 几根向 d 方向伸出的指（d 为单位方向）。"""
    import mathutils
    p, d = mathutils.Vector(p), mathutils.Vector(d).normalized()
    side = d.cross(mathutils.Vector((0, 0, 1)))
    if side.length < 0.1:
        side = mathutils.Vector((1, 0, 0))
    side.normalize()
    lp.ball(tuple(p), (r, r, r * 0.8), color)
    for i in range(fingers):
        o = (i - (fingers - 1) / 2) * r * 0.7
        a = p + d * r * 0.6 + side * o
        b = a + d * length + mathutils.Vector((0, 0, -length * 0.4))
        lp.capsule(tuple(a), tuple(b), r * 0.28, color, radius2=r * 0.12, seg=8)


