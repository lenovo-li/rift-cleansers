"""四个可玩角色（铁卫、元素术士、影行者、牧师）。约 1.8-1.9 米，面朝 +Y，+x 为角色左侧。
分组（lp.group）和关节位置必须与 build_models.RIGS 一致：手臂零件要以肩关节为轴摆动。"""
import math

import lowpoly as lp
from palette import BLACK, CLOTH_DARK, GOLD, LEATHER, LEATHER_DARK, SKIN, STEEL, STEEL_DARK, TEAM, WHITE


def _boot(x, color, toe=0.32, h=0.16):
    """靴子：脚掌圆角块 + 鞋尖球 + 靴筒。"""
    lp.box((x, 0.04, h * 0.32), (0.2, toe * 0.75, h * 0.64), color, bevel=0.03)
    lp.ball((x, 0.04 + toe * 0.36, h * 0.3), (0.095, 0.08, h * 0.3), color)
    lp.cyl((x, -0.01, h * 0.85), 0.1, h * 0.7, color, radius2=0.09)


def _hand(x, y, z, color, r=0.055):
    """握拳的手：掌 + 拇指。"""
    lp.ball((x, y, z), (r, r * 1.1, r * 1.15), color)
    lp.capsule((x + (0.03 if x > 0 else -0.03), y + 0.03, z + 0.02), (x, y + 0.055, z + 0.01), r * 0.38, color)


def _face(z, y, skin, eye=BLACK, brow=None, r=0.14):
    """头 + 鼻 + 眼 + 耳（头半径 r，中心在 (0, y, z)）。"""
    lp.ball((0, y, z), (r, r * 1.02, r * 1.1), skin)
    lp.ball((0, y + r * 0.98, z - r * 0.08), (r * 0.16, r * 0.2, r * 0.22), lp.shade(skin, 0.95))
    for x in (r * 0.38, -r * 0.38):
        lp.ball((x, y + r * 0.86, z + r * 0.1), (r * 0.12, r * 0.08, r * 0.14), eye, ao=0)
        lp.ball((x * 2.5, y - r * 0.05, z), (r * 0.12, r * 0.2, r * 0.25), lp.shade(skin, 0.92))
        if brow is not None:
            lp.box((x, y + r * 0.9, z + r * 0.32), (r * 0.42, r * 0.1, r * 0.1), brow, rot=(0, -12 if x > 0 else 12, 0))


