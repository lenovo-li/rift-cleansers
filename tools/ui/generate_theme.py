def make_font():
    w, h = 128, 96  # 16 列 × 12 行，每格 8x8
    rgba = bytearray(w * h * 4)
    for code in range(32, 127):
        bits = FONT.get(code, [0] * 8)
        cx, cy = (code - 32) % 16, (code - 32) // 16
        for row in range(8):
            for col in range(8):
                if bits[row] & (1 << (7 - col)):
                    idx = ((cy * 8 + row) * w + cx * 8 + col) * 4
                    rgba[idx:idx + 4] = [255, 255, 255, 255]
    save_png(os.path.join(OUT, "font_bitmap.png"), w, h, bytes(rgba))


def make_button(name, border, fill):
    """生成 32x32 九宫格按钮（边框 4 像素）。"""
    w, h = 32, 32
    rgba = bytearray(w * h * 4)
    for y in range(h):
        for x in range(w):
            is_border = x < 4 or x >= 28 or y < 4 or y >= 28
            color = border if is_border else fill
            idx = (y * w + x) * 4
            rgba[idx:idx + 4] = color
    save_png(os.path.join(OUT, name + ".png"), w, h, bytes(rgba))


def make_panel():
    """生成 64x64 半透明面板背景（九宫格，边框 8 像素）。"""
    w, h = 64, 64
    rgba = bytearray(w * h * 4)
    for y in range(h):
        for x in range(w):
            is_border = x < 8 or x >= 56 or y < 8 or y >= 56
            if is_border:
                rgba[(y * w + x) * 4:(y * w + x) * 4 + 4] = [40, 40, 50, 200]
            else:
                rgba[(y * w + x) * 4:(y * w + x) * 4 + 4] = [25, 25, 35, 180]
    save_png(os.path.join(OUT, "panel_bg.png"), w, h, bytes(rgba))


